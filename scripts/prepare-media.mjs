import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import sharp from 'sharp';
import ffmpeg from 'ffmpeg-static';
import { hashFile } from './audit-assets.mjs';

const root = process.cwd();
assert(fs.existsSync('scripts/media-sources.json'), 'Run node scripts/optimize-assets.mjs --samples first');
const config = JSON.parse(fs.readFileSync('scripts/media-sources.json', 'utf8'));
const originals = path.resolve(process.env.MUSEUM_ORIGINALS || config.originalsRoot);
const relative = path.relative(root, originals);
assert(relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative), 'Originals must be outside the deploy workspace');
const manifest = {};
fs.mkdirSync('assets/media', { recursive: true });
fs.mkdirSync('.museum-checks/asset-optimization/poster-frames', { recursive: true });
const outputFile = url => {
  const file = path.resolve(root, `.${url}`);
  assert(file.startsWith(path.join(root, 'assets') + path.sep));
  fs.mkdirSync(path.dirname(file), { recursive: true });
  return file;
};

async function createVariants(source, large, thumb, quality = config.quality) {
  // Sharp strips metadata by default; bake EXIF orientation first, then encode sRGB pixels.
  const input = () => sharp(source).autoOrient().toColourspace('srgb');
  await input().resize({ width: config.largeMax, height: config.largeMax, fit: 'inside', withoutEnlargement: true }).webp({ quality, effort: 6 }).toFile(outputFile(large));
  await input().resize({ width: config.thumbnailMax, height: config.thumbnailMax, fit: 'inside', withoutEnlargement: true }).webp({ quality, effort: 6 }).toFile(outputFile(thumb));
  const metadata = await sharp(`.${large}`).metadata();
  const small = await sharp(`.${thumb}`).metadata();
  const preview = await input().resize(20, 20, { fit: 'inside', withoutEnlargement: true }).webp({ quality: 30 }).toBuffer();
  assert(!metadata.exif && !metadata.icc && !metadata.orientation);
  return { large, thumb, width: metadata.width, height: metadata.height, thumbWidth: small.width, thumbHeight: small.height, preview: `data:image/webp;base64,${preview.toString('base64')}`, quality };
}

for (const photo of config.photos) {
  const source = path.resolve(originals, photo.original);
  assert(source.startsWith(originals + path.sep), 'Source outside original backup');
  assert.equal(hashFile(source), photo.sha256, `Original backup integrity: ${photo.original}`);
  manifest[photo.large] = await createVariants(source, photo.large, photo.thumb, photo.quality);
}

// Extract still posters only. Never encode, replace, move, or recompress any video.
for (const [index, poster] of config.videoPosters.entries()) {
  const source = `.${poster.src}`;
  const playback = `.${poster.playback}`;
  assert(fs.existsSync(source) && fs.existsSync(playback), `Missing existing video: ${poster.src}`);
  const sourceHash = hashFile(source);
  const playbackHash = hashFile(playback);
  const frame = `.museum-checks/asset-optimization/poster-frames/${index}.png`;
  execFileSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-y', '-ss', String(poster.posterTime), '-i', source, '-frames:v', '1', frame]);
  manifest[poster.src] = { ...await createVariants(frame, poster.large, poster.thumb), playback: poster.playback, posterTime: poster.posterTime };
  assert.equal(hashFile(source), sourceHash, 'Original video unchanged');
  assert.equal(hashFile(playback), playbackHash, 'Existing playback unchanged');
  fs.unlinkSync(frame);
}
fs.writeFileSync('assets/media/manifest.js', `// Generated by npm run media. JPEG originals live outside the deploy workspace.\nwindow.museumMedia = ${JSON.stringify(manifest)};\n`);

const runtimeFiles = fs.readdirSync(root).filter(file => /\.(html|css|js)$/.test(file));
const sources = new Map();
for (const photo of config.photos) {
  const entry = manifest[photo.large];
  for (const [url, size] of [[photo.large, 'large'], [photo.thumb, 'thumb'], [photo.legacy?.large, 'large'], [photo.legacy?.thumb, 'thumb']]) {
    if (url) sources.set(url, { entry, size });
  }
}
for (const poster of config.videoPosters) {
  const entry = manifest[poster.src];
  for (const [url, size] of [[poster.large, 'large'], [poster.thumb, 'thumb'], [poster.legacy.large, 'large'], [poster.legacy.thumb, 'thumb']]) sources.set(url, { entry, size });
}
for (const file of runtimeFiles) {
  let content = fs.readFileSync(file, 'utf8');
  if (file.endsWith('.html')) {
    content = content.replace(/<span class="([^"]*\bmedia-image\b[^"]*)" style="[^"]*"><img([^>]*?)\/><\/span>/g, (tag, classes, attributes) => {
      const src = attributes.match(/\bsrc="([^"]+)"/)?.[1];
      const source = sources.get(src);
      if (!source) throw new Error(`Unknown static image in ${file}: ${src}`);
      const { entry, size } = source;
      const sizes = attributes.match(/\bsizes="([^"]+)"/)?.[1] || '(max-width: 520px) 50vw, 650px';
      attributes = attributes.replace(/\s+(srcset|sizes|width|height)="[^"]*"/g, '').replace(/\bsrc="[^"]+"/, `src="${entry[size]}"`);
      const responsive = size === 'large' && entry.thumbWidth < entry.width ? ` srcset="${entry.thumb} ${entry.thumbWidth}w, ${entry.large} ${entry.width}w" sizes="${sizes}"` : '';
      const width = size === 'thumb' ? entry.thumbWidth : entry.width;
      const height = size === 'thumb' ? entry.thumbHeight : entry.height;
      return `<span class="${classes}" style="--media-preview: url('${entry.preview}')"><img${attributes}${responsive} width="${width}" height="${height}" /></span>`;
    });
  }
  for (const photo of config.photos) {
    content = content.replaceAll(`/${photo.original}`, photo.large);
    if (file === 'data.js') content = content.replaceAll(`"${path.posix.basename(photo.original)}"`, `"${path.posix.basename(photo.large)}"`);
  }
  if (file === 'data.js') content = content.replaceAll('"cover.jpeg"', '"cover.webp"');
  for (const [legacy, { entry, size }] of sources) content = content.replaceAll(legacy, entry[size]);
  if (content !== fs.readFileSync(file, 'utf8')) fs.writeFileSync(file, content);
}
const data = { window: {} };
vm.runInNewContext(fs.readFileSync('data.js', 'utf8'), data);
for (const album of data.window.gallery) {
  for (const src of [...album.photos, ...album.videos]) assert(manifest[src], `Missing runtime mapping: ${src}`);
}
console.log(`Prepared ${config.photos.length} photos (max 1920), 800px thumbnails and ${config.videoPosters.length} still posters. All videos remained byte-identical.`);
